import { network } from "hardhat";
import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

async function main() {
  const { ethers } = await network.create();

  console.log("Deploying AgriculturalSupplyChain...\n");

  const [deployer] = await ethers.getSigners();
  console.log(`Deployer: ${deployer.address}`);
  console.log(
    `Balance:  ${ethers.formatEther(await ethers.provider.getBalance(deployer.address))} ETH\n`
  );

  const Factory = await ethers.getContractFactory("AgriculturalSupplyChain");
  const contract = await Factory.deploy();
  await contract.waitForDeployment();

  const address = await contract.getAddress();
  console.log(`✅ Contract deployed to: ${address}`);

  // Write contract address to frontend config
  const frontendContractDir = path.join(__dirname, "../frontend/src/contracts");
  fs.mkdirSync(frontendContractDir, { recursive: true });

  const addressFile = path.join(frontendContractDir, "contractAddress.js");
  fs.writeFileSync(
    addressFile,
    `// Auto-generated by deploy.ts — do not edit manually\nexport const CONTRACT_ADDRESS = "${address}";\nexport const NETWORK_CHAIN_ID = 31337;\n`
  );
  console.log(`📝 Contract address written to ${addressFile}`);

  // Copy ABI to frontend
  const artifactPath = path.join(
    __dirname,
    "../artifacts/contracts/AgriculturalSupplyChain.sol/AgriculturalSupplyChain.json"
  );

  if (fs.existsSync(artifactPath)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
    const abiFile = path.join(frontendContractDir, "AgriculturalSupplyChain.json");
    fs.writeFileSync(abiFile, JSON.stringify({ abi: artifact.abi }, null, 2));
    console.log(`📝 ABI written to ${abiFile}`);
  } else {
    console.warn("⚠️  Artifact not found — run 'npx hardhat compile' first");
  }

  console.log("\n🎉 Deployment complete!");
  console.log(`\nNext: run 'npx hardhat run scripts/seedDemoData.ts --network localhost'`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
