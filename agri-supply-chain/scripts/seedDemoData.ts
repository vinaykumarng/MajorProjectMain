import { network } from "hardhat";
import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from "url";

/**
 * seedDemoData.ts
 *
 * Authorises four demo participant accounts (Farmer, Processor, Distributor, Retailer)
 * using the Hardhat test accounts (indices 1–4), then registers a sample batch
 * RICE-2026-001 from the Farmer account.
 *
 * Hardhat local node account layout (from `npx hardhat node`):
 *   [0] Owner  / Admin      — deploys contract
 *   [1] Farmer              — registers batches
 *   [2] Processor
 *   [3] Distributor
 *   [4] Retailer
 */

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const Role = {
  FARMER: 2,
  PROCESSOR: 3,
  DISTRIBUTOR: 4,
  RETAILER: 5,
};

async function main() {
  const { ethers } = await network.create();

  const signers = await ethers.getSigners();
  const [admin, farmer, processor, distributor, retailer] = signers;

  // Resolve contract address
  const addressFile = path.join(__dirname, "../frontend/src/contracts/contractAddress.js");
  if (!fs.existsSync(addressFile)) {
    throw new Error("contractAddress.js not found — run deploy.ts first");
  }
  const addressContent = fs.readFileSync(addressFile, "utf8");
  const match = addressContent.match(/CONTRACT_ADDRESS = "([^"]+)"/);
  if (!match || !match[1]) {
    throw new Error("Could not parse CONTRACT_ADDRESS from contractAddress.js — deploy first");
  }
  const contractAddress = match[1];

  console.log(`📦 Connecting to contract at ${contractAddress}\n`);

  const contract = await ethers.getContractAt("AgriculturalSupplyChain", contractAddress);

  // Authorize participants
  console.log("Authorizing participants...");
  const roles = [
    { signer: farmer, name: "Farmer", role: Role.FARMER },
    { signer: processor, name: "Processor", role: Role.PROCESSOR },
    { signer: distributor, name: "Distributor", role: Role.DISTRIBUTOR },
    { signer: retailer, name: "Retailer", role: Role.RETAILER },
  ];

  for (const { signer, name, role } of roles) {
    const tx = await contract.connect(admin).authorizeParticipant(signer.address, role);
    await tx.wait();
    console.log(`  ✅ ${name}: ${signer.address}`);
  }

  // Register demo batch
  console.log("\nRegistering demo batch RICE-2026-001...");
  const harvestDate = Math.floor(Date.now() / 1000) - 3 * 86400; // 3 days ago

  const tx = await (contract as any).connect(farmer).registerBatch(
    "RICE-2026-001",
    "Basmati Rice",
    "Rice",
    5000,
    "kg",
    "Punjab, India — Amritsar District",
    harvestDate,
    "Grade A premium basmati. Pesticide-free. Irrigated organically."
  );
  await tx.wait();
  console.log("  ✅ Batch RICE-2026-001 registered by Farmer");

  // Save demo accounts info for the frontend
  const demoAccountsFile = path.join(__dirname, "../frontend/src/contracts/demoAccounts.js");
  const demoAccounts = {
    admin: { address: admin.address, role: "ADMIN" },
    farmer: { address: farmer.address, role: "FARMER" },
    processor: { address: processor.address, role: "PROCESSOR" },
    distributor: { address: distributor.address, role: "DISTRIBUTOR" },
    retailer: { address: retailer.address, role: "RETAILER" },
  };
  fs.writeFileSync(
    demoAccountsFile,
    `// Auto-generated by seedDemoData.ts\nexport const DEMO_ACCOUNTS = ${JSON.stringify(demoAccounts, null, 2)};\n`
  );
  console.log(`\n📝 Demo accounts written to ${demoAccountsFile}`);

  console.log("\n🎉 Demo data seeded successfully!");
  console.log("\n📋 Demo Account Summary:");
  console.log(`   Admin       : ${admin.address}`);
  console.log(`   Farmer      : ${farmer.address}`);
  console.log(`   Processor   : ${processor.address}`);
  console.log(`   Distributor : ${distributor.address}`);
  console.log(`   Retailer    : ${retailer.address}`);
  console.log("\n   Sample Batch: RICE-2026-001 (currently with Farmer)");
  console.log("\n   Import these private keys into MetaMask from the Hardhat node output.");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
